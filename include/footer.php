document.addEventListener('DOMContentLoaded', function () {

    const modalElement = document.getElementById('documentModal');
    const modal = new bootstrap.Modal(modalElement);
    const form = document.getElementById('documentDownloadForm');
    const submitBtn = document.getElementById('documentSubmitBtn');
    const message = document.getElementById('documentFormMessage');

    let selectedDocument = '';

    // PDF document paths
    const documents = {
        'legal': {
            name: 'Legal Document',
            url: 'documents/legal.pdf'
        },
        'vendor-approval': {
            name: 'Vendor Approval Document',
            url: 'documents/vendor-approval.pdf'
        }
    };

    // Open modal
    document.querySelectorAll('.document-download').forEach(link => {
        link.addEventListener('click', function (e) {
            e.preventDefault();

            selectedDocument = this.dataset.document;

            document.getElementById('documentModalTitle').textContent =
                'Download ' + this.dataset.title;

            document.getElementById('documentName').value =
                documents[selectedDocument].name;

            message.textContent = '';
            form.reset();
            document.getElementById('documentName').value =
                documents[selectedDocument].name;

            modal.show();
        });
    });

    // Submit form
    form.addEventListener('submit', async function (e) {
        e.preventDefault();

        submitBtn.disabled = true;
        submitBtn.textContent = 'Please wait...';
        message.textContent = '';

        try {
            const response = await fetch('https://formspree.io/f/YOUR_FORM_ID', {
                method: 'POST',
                body: new FormData(form),
                headers: {
                    'Accept': 'application/json'
                }
            });

            if (response.ok) {
                const downloadLink = document.createElement('a');
                downloadLink.href = documents[selectedDocument].url;
                downloadLink.download = '';
                document.body.appendChild(downloadLink);
                downloadLink.click();
                downloadLink.remove();

                message.textContent = 'Details submitted! Your download is starting.';
                message.style.color = 'green';

                form.reset();

                setTimeout(() => {
                    modal.hide();
                }, 1500);

            } else {
                message.textContent = 'Unable to submit your details. Please try again.';
                message.style.color = 'red';
            }

        } catch (error) {
            message.textContent = 'Something went wrong. Please try again.';
            message.style.color = 'red';
        }

        submitBtn.disabled = false;
        submitBtn.textContent = 'Download Document';
    });

});
